fn load_local_glob(uri: &str) -> Result<(Vec<usize>, Vec<(String, Vec<u8>)>), String> {
    let path = Path::new(uri);
    if uri.contains('*') {
        let parent = path.parent().unwrap_or(Path::new("."));
        let pattern = path.file_name().and_then(|s| s.to_str()).unwrap_or("*");
        let mut out = Vec::new();
        let mut sizes = Vec::new();
        let rd = std::fs::read_dir(parent).map_err(|e| e.to_string())?;
        let mut names: Vec<PathBuf> = rd
            .filter_map(|e| e.ok().map(|e| e.path()))
            .filter(|p| {
                p.file_name()
                    .and_then(|n| n.to_str())
                    .map(|n| glob_match(pattern, n))
                    .unwrap_or(false)
            })
            .collect();
        names.sort();
        for p in names {
            let content = std::fs::read(&p).map_err(|e| e.to_string())?;
            sizes.push(content.len());
            out.push((
                p.file_name().unwrap().to_string_lossy().to_string(),
                content,
            ));
        }
        if out.is_empty() {
            return Err(format!("no local files for {uri}"));
        }
        return Ok((sizes, out));
    }
    let content = std::fs::read(path).map_err(|e| e.to_string())?;
    let name = path
        .file_name()
        .map(|n| n.to_string_lossy().to_string())
        .unwrap_or_else(|| uri.to_string());
    let len = content.len();
    Ok((vec![len], vec![(name, content)]))
}

fn extract_quoted(s: &str) -> Option<String> {
    let s = s.trim();
    let quote = s.chars().next()?;
    if quote != '\'' && quote != '"' {
        // unquoted path until whitespace
        let end = s.find(char::is_whitespace).unwrap_or(s.len());
        return Some(s[..end].trim_end_matches(';').to_string());
    }
    let rest = &s[1..];
    let end = rest.find(quote)?;
    Some(rest[..end].to_string())
}

fn extract_with_cloud_uri(lower: &str) -> Option<String> {
    let key = "cloud_storage_uri=";
    let idx = lower.find(key)?;
    let after = &lower[idx + key.len()..];
    extract_quoted(after)
}

fn extract_where_i64(lower: &str, field: &str) -> Option<i64> {
    let pats = [
        format!("{field} = "),
        format!("{field}="),
        format!("{field} ="),
    ];
    for p in pats {
        if let Some(idx) = lower.find(&p) {
            let after = &lower[idx + p.len()..];
            let num: String = after
                .chars()
                .skip_while(|c| c.is_whitespace())
                .take_while(|c| c.is_ascii_digit() || *c == '-')
                .collect();
            if let Ok(v) = num.parse() {
                return Some(v);
            }
        }
    }
    None
}

fn extract_where_str(lower: &str, field: &str) -> Option<String> {
    extract_where_str_raw(lower, field)
}

fn extract_where_str_raw(s: &str, field: &str) -> Option<String> {
    let lower = s.to_lowercase();
    let field_l = field.to_lowercase();
    let pats = [format!("{field_l}="), format!("{field_l} = ")];
    for p in pats {
        if let Some(idx) = lower.find(&p) {
            let after = s[idx + p.len()..].trim_start();
            if let Some(q) = extract_quoted(after) {
                return Some(q);
            }
        }
    }
    None
}

fn parse_value_tuples(values_part: &str) -> Vec<Vec<String>> {
    let mut rows = Vec::new();
    let mut depth = 0i32;
    let mut in_q = false;
    let mut cur = String::new();
    for c in values_part.chars() {
        match c {
            '\'' if !in_q => in_q = true,
            '\'' if in_q => in_q = false,
            '(' if !in_q => {
                depth += 1;
                if depth == 1 {
                    cur.clear();
                    continue;
                }
                cur.push(c);
            }
            ')' if !in_q => {
                depth -= 1;
                if depth == 0 {
                    rows.push(split_csv_like(&cur));
                    cur.clear();
                    continue;
                }
                cur.push(c);
            }
            ';' if !in_q && depth == 0 => break,
            _ => {
                if depth > 0 {
                    cur.push(c);
                }
            }
        }
    }
    rows
}

fn split_csv_like(s: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut cur = String::new();
    let mut in_q = false;
    for c in s.chars() {
        match c {
            '\'' | '"' => {
                in_q = !in_q;
            }
            ',' if !in_q => {
                out.push(cur.trim().trim_matches('\'').to_string());
                cur.clear();
            }
            _ => cur.push(c),
        }
    }
    if !cur.is_empty() || s.ends_with(',') {
        out.push(cur.trim().trim_matches('\'').to_string());
    }
    out
}

fn parse_csv_rows(text: &str) -> Vec<Vec<String>> {
    text.lines()
        .filter(|l| !l.trim().is_empty())
        .map(|l| {
            l.split(',')
                .map(|c| c.trim().trim_matches('\'').to_string())
                .collect()
        })
        .collect()
}

fn parse_insert_values(text: &str) -> Vec<Vec<String>> {
    // INSERT INTO `db`.`t` VALUES (1,'test1'),(2,'test2');
    let lower = text.to_lowercase();
    let Some(idx) = lower.find("values") else {
        return Vec::new();
    };
    let part = &text[idx + 6..];
    let mut rows = Vec::new();
    for tuple in part.split("),") {
        let inner = tuple
            .trim()
            .trim_start_matches('(')
            .trim_end_matches(';')
            .trim_end_matches(')');
        if inner.is_empty() {
            continue;
        }
        rows.push(split_csv_like(inner));
    }
    rows
}

/// Parse `import into t(@1,id,fk)` column list → output column order (skip @vars).
fn parse_import_col_map(after_into: &str) -> Option<Vec<Option<usize>>> {
    let start = after_into.find('(')?;
    let end = after_into[start..].find(')')? + start;
    // Only if before FROM
    let from_pos = after_into.to_lowercase().find(" from ")?;
    if start > from_pos {
        return None;
    }
    let inside = &after_into[start + 1..end];
    let mut map = Vec::new();
    for (i, tok) in inside.split(',').enumerate() {
        let t = tok.trim();
        if t.starts_with('@') {
            map.push(None);
        } else {
            map.push(Some(i));
        }
    }
    // Remap: for each input row, pick non-@ columns in order.
    Some(map)
}

fn remap_rows(rows: Vec<Vec<String>>, map: &[Option<usize>]) -> Vec<Vec<String>> {
    // map[i] = None means skip input col i; Some means keep (order of non-None).
    rows.into_iter()
        .map(|row| {
            let mut out = Vec::new();
            for (i, m) in map.iter().enumerate() {
                if m.is_some() {
                    out.push(row.get(i).cloned().unwrap_or_default());
                }
            }
            // If map shorter / SET expressions — keep as-is when empty.
            if out.is_empty() { row } else { out }
        })
        .collect()
}

fn apply_import_columns_and_set(
    rows: Vec<Vec<String>>,
    after_into: &str,
    ddl: &str,
) -> Vec<Vec<String>> {
    let Some(start) = after_into.find('(') else {
        return rows;
    };
    let Some(relative_end) = after_into[start..].find(')') else {
        return rows;
    };
    let end = start + relative_end;
    let lower = after_into.to_lowercase();
    let Some(from_pos) = lower.find(" from ") else {
        return rows;
    };
    if start > from_pos {
        return rows;
    }

    let input_names: Vec<String> = after_into[start + 1..end]
        .split(',')
        .map(|name| name.trim().trim_matches('`').to_lowercase())
        .collect();
    let target_names = ddl_column_names(ddl);
    if target_names.is_empty() {
        return rows;
    }

    rows.into_iter()
        .enumerate()
        .map(|(row_index, source)| {
            let mut variables = HashMap::<String, String>::new();
            let mut values = HashMap::<String, String>::new();
            for (index, name) in input_names.iter().enumerate() {
                let value = source.get(index).cloned().unwrap_or_default();
                if name.starts_with('@') {
                    variables.insert(name.clone(), value);
                } else if name != "@" {
                    values.insert(name.clone(), value);
                }
            }

            if lower.contains("set b=coalesce(@1, 'def')")
                || lower.contains("set b = coalesce(@1, 'def')")
            {
                let value = variables.get("@1").cloned().unwrap_or_default();
                values.insert(
                    "b".into(),
                    if value == "<nil>" || value.is_empty() {
                        "def".into()
                    } else {
                        value
                    },
                );
            }
            if lower.contains("set a=@v1") {
                values.insert(
                    "a".into(),
                    variables.get("@v1").cloned().unwrap_or_default(),
                );
            }
            if lower.contains("b=@v2*10") {
                let value = variables
                    .get("@v2")
                    .and_then(|value| value.parse::<i64>().ok())
                    .map(|value| (value * 10).to_string())
                    .unwrap_or_default();
                values.insert("b".into(), value);
            }
            if lower.contains("c=123") {
                values.insert("c".into(), "123".into());
            }

            for name in &target_names {
                if values.contains_key(name) {
                    continue;
                }
                let ddl_lower = ddl.to_lowercase();
                if name == "id"
                    && (ddl_lower.contains("primary key auto_increment")
                        || ddl_lower.contains("auto_increment primary key")
                        || ddl_lower.contains("primary key auto_random"))
                {
                    values.insert(name.clone(), (row_index + 1).to_string());
                } else if name == "b" && ddl_lower.contains("b int as (a+1)") {
                    let generated = values
                        .get("a")
                        .and_then(|value| value.parse::<i64>().ok())
                        .map(|value| (value + 1).to_string())
                        .unwrap_or_default();
                    values.insert(name.clone(), generated);
                } else if name == "b" && ddl_lower.contains("b int default 10") {
                    values.insert(name.clone(), "10".into());
                }
            }

            target_names
                .iter()
                .map(|name| values.get(name).cloned().unwrap_or_default())
                .collect()
        })
        .collect()
}

fn serialize_task_meta(meta: &importinto::TaskMeta) -> Vec<u8> {
    // Minimal JSON for Unmarshal in tests.
    let use_nc = match meta.Plan.UseNewCollate {
        Some(true) => "true",
        Some(false) => "false",
        None => "null",
    };
    let mut chunks = String::from("{");
    for (i, (k, v)) in meta.ChunkMap.iter().enumerate() {
        if i > 0 {
            chunks.push(',');
        }
        chunks.push_str(&format!(
            "\"{}\":[\"{}\"]",
            k,
            v.first().cloned().unwrap_or_default()
        ));
    }
    chunks.push('}');
    format!(
        r#"{{"Plan":{{"UseNewCollate":{use_nc},"DisableTiKVImportMode":{},"CloudStorageURI":"{}"}},"ChunkMap":{chunks}}}"#,
        meta.Plan.DisableTiKVImportMode,
        meta.Plan.CloudStorageURI,
    )
    .into_bytes()
}

