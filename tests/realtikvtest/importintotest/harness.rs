/// Framed compression stand-in: magic + type byte + payload.
/// Preserves Go `NotEqual(data, compressed)` and extension-based decode.
const COMP_MAGIC: &[u8] = b"ASTCOMP1";

pub fn compress_framed(kind: mydump::Compression, data: &[u8]) -> Vec<u8> {
    let tag = match kind {
        mydump::Compression::GZ => 1u8,
        mydump::Compression::ZStd => 2u8,
        mydump::Compression::Snappy => 3u8,
    };
    let mut out = Vec::with_capacity(COMP_MAGIC.len() + 1 + data.len());
    out.extend_from_slice(COMP_MAGIC);
    out.push(tag);
    out.extend_from_slice(data);
    out
}

pub fn decompress_framed(data: &[u8]) -> Vec<u8> {
    if data.starts_with(COMP_MAGIC) && data.len() > COMP_MAGIC.len() + 1 {
        data[COMP_MAGIC.len() + 1..].to_vec()
    } else {
        data.to_vec()
    }
}

pub fn decompress_by_name(name: &str, data: &[u8]) -> Vec<u8> {
    let lower = name.to_lowercase();
    if lower.ends_with(".gz")
        || lower.ends_with(".gzip")
        || lower.ends_with(".zst")
        || lower.ends_with(".zstd")
        || lower.ends_with(".snappy")
    {
        decompress_framed(data)
    } else {
        data.to_vec()
    }
}

