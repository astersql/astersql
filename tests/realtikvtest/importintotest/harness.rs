pub mod handle {
    use super::{kerneltype, proto, schstatus};

    pub fn GetScheduleStatus(_ctx: ()) -> Result<schstatus::Status, String> {
        let e = super::eng();
        let cpu_count = super::mocked_cpu_count();
        let mut available_cpu = Vec::<i32>::new();
        for task in e
            .tasks
            .values()
            .filter(|task| task.State == proto::TaskStateRunning || task.State == "modifying")
        {
            let mut needed_nodes = if task.Type == proto::ImportInto
                && matches!(
                    task.Step,
                    proto::ImportStepCollectConflicts
                        | proto::ImportStepConflictResolution
                        | proto::ImportStepPostProcess
                ) {
                1
            } else {
                task.MaxNodeCount.max(1)
            };
            for available in &mut available_cpu {
                if needed_nodes == 0 {
                    break;
                }
                if *available >= task.RequiredSlots {
                    *available -= task.RequiredSlots;
                    needed_nodes -= 1;
                }
            }
            for _ in 0..needed_nodes {
                available_cpu.push((cpu_count - task.RequiredSlots).max(0));
            }
        }
        let required = if kerneltype::IsNextGen() {
            available_cpu.len().max(1) as i32
        } else {
            1
        };
        Ok(schstatus::Status {
            TiDBWorker: schstatus::WorkerStatus {
                RequiredCount: required,
            },
        })
    }
}

