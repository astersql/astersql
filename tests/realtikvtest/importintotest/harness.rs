pub mod mode_switcher {
    use super::*;
    use std::sync::atomic::{AtomicI32, Ordering};
    use std::time::Instant;

    static IMPORT_CALLS: AtomicI32 = AtomicI32::new(0);
    static NORMAL_CALLS: AtomicI32 = AtomicI32::new(0);
    static LAST_IMPORT: OnceLock<Mutex<Option<Instant>>> = OnceLock::new();
    static LAST_NORMAL: OnceLock<Mutex<Option<Instant>>> = OnceLock::new();
    static HOOK_IMPORT: OnceLock<Mutex<Option<Arc<dyn Fn() + Send + Sync>>>> = OnceLock::new();
    static HOOK_NORMAL: OnceLock<Mutex<Option<Arc<dyn Fn() + Send + Sync>>>> = OnceLock::new();

    pub fn reset() {
        IMPORT_CALLS.store(0, Ordering::SeqCst);
        NORMAL_CALLS.store(0, Ordering::SeqCst);
        *LAST_IMPORT.get_or_init(|| Mutex::new(None)).lock().unwrap() = None;
        *LAST_NORMAL.get_or_init(|| Mutex::new(None)).lock().unwrap() = None;
        *HOOK_IMPORT.get_or_init(|| Mutex::new(None)).lock().unwrap() = None;
        *HOOK_NORMAL.get_or_init(|| Mutex::new(None)).lock().unwrap() = None;
    }

    pub fn set_hooks(
        on_import: Option<Arc<dyn Fn() + Send + Sync>>,
        on_normal: Option<Arc<dyn Fn() + Send + Sync>>,
    ) {
        *HOOK_IMPORT.get_or_init(|| Mutex::new(None)).lock().unwrap() = on_import;
        *HOOK_NORMAL.get_or_init(|| Mutex::new(None)).lock().unwrap() = on_normal;
    }

    pub fn ToImportMode() {
        IMPORT_CALLS.fetch_add(1, Ordering::SeqCst);
        *LAST_IMPORT.get_or_init(|| Mutex::new(None)).lock().unwrap() = Some(Instant::now());
        if let Some(h) = HOOK_IMPORT
            .get_or_init(|| Mutex::new(None))
            .lock()
            .unwrap()
            .as_ref()
        {
            h();
        }
    }

    pub fn ToNormalMode() {
        NORMAL_CALLS.fetch_add(1, Ordering::SeqCst);
        *LAST_NORMAL.get_or_init(|| Mutex::new(None)).lock().unwrap() = Some(Instant::now());
        if let Some(h) = HOOK_NORMAL
            .get_or_init(|| Mutex::new(None))
            .lock()
            .unwrap()
            .as_ref()
        {
            h();
        }
    }

    pub fn into_import_time() -> Option<Instant> {
        *LAST_IMPORT.get_or_init(|| Mutex::new(None)).lock().unwrap()
    }
    pub fn into_normal_time() -> Option<Instant> {
        *LAST_NORMAL.get_or_init(|| Mutex::new(None)).lock().unwrap()
    }
    pub fn import_calls() -> i32 {
        IMPORT_CALLS.load(Ordering::SeqCst)
    }
    pub fn normal_calls() -> i32 {
        NORMAL_CALLS.load(Ordering::SeqCst)
    }
}

