pub mod etcd {
    use super::*;
    use std::collections::BTreeMap;

    static KV: OnceLock<Mutex<BTreeMap<String, Vec<u8>>>> = OnceLock::new();

    fn slot() -> &'static Mutex<BTreeMap<String, Vec<u8>>> {
        KV.get_or_init(|| Mutex::new(BTreeMap::new()))
    }

    pub fn reset() {
        slot().lock().unwrap().clear();
    }

    #[derive(Clone, Debug)]
    pub struct GetResponse {
        pub Kvs: Vec<(String, Vec<u8>)>,
    }

    #[derive(Clone, Debug)]
    pub struct Client;

    impl Client {
        pub fn new() -> Self {
            Self
        }
        pub fn Close(&self) -> Result<(), String> {
            Ok(())
        }
        pub fn Put(&self, _ctx: (), key: &str, val: &str) -> Result<(), String> {
            slot()
                .lock()
                .unwrap()
                .insert(key.to_string(), val.as_bytes().to_vec());
            if key.starts_with(&super::streamhelper::PrefixOfTask()) {
                let name = key
                    .trim_start_matches(&super::streamhelper::PrefixOfTask())
                    .to_string();
                let mut e = super::eng();
                if !e.pitr_tasks.iter().any(|t| t == &name) {
                    e.pitr_tasks.push(name);
                }
            }
            if key.contains("/tidb/cdc/") && key.contains("/changefeed/info/") {
                // /tidb/cdc/{cluster}/{ns}/changefeed/info/{feed}
                let parts: Vec<_> = key.split('/').collect();
                // ["", "tidb", "cdc", cluster, ns, "changefeed", "info", feed]
                if parts.len() >= 8 {
                    let cluster_ns = format!("{}/{}", parts[3], parts[4]);
                    let feed = parts[7].to_string();
                    let mut e = super::eng();
                    e.cdc_feeds.push((cluster_ns, feed));
                }
            }
            Ok(())
        }
        pub fn Delete(&self, _ctx: (), key: &str) -> Result<(), String> {
            slot().lock().unwrap().remove(key);
            if key.starts_with(&super::streamhelper::PrefixOfTask()) {
                let name = key
                    .trim_start_matches(&super::streamhelper::PrefixOfTask())
                    .to_string();
                super::eng().pitr_tasks.retain(|t| t != &name);
            }
            if key.contains("/tidb/cdc/") && key.contains("/changefeed/info/") {
                let parts: Vec<_> = key.split('/').collect();
                if parts.len() >= 8 {
                    let feed = parts[7].to_string();
                    super::eng().cdc_feeds.retain(|(_, f)| f != &feed);
                }
            }
            Ok(())
        }
        pub fn Get(&self, _ctx: (), key: &str) -> Result<GetResponse, String> {
            let g = slot().lock().unwrap();
            let Kvs = g
                .get(key)
                .map(|v| vec![(key.to_string(), v.clone())])
                .unwrap_or_default();
            Ok(GetResponse { Kvs })
        }
    }
}

