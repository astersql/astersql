fn extract_i64_field(s: &str, key: &str) -> Option<i64> {
    let pat = format!("\"{key}\"");
    let idx = s.find(&pat)?;
    let after = &s[idx + pat.len()..];
    let after = after.trim_start_matches(|c: char| c == ':' || c.is_whitespace());
    let num: String = after
        .chars()
        .take_while(|c| c.is_ascii_digit() || *c == '-')
        .collect();
    num.parse().ok()
}

