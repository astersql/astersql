fn parse_usize_option(sql: &str, name: &str) -> Option<usize> {
    let start = sql.find(name)? + name.len();
    let tail = sql[start..].trim_start();
    let tail = tail.strip_prefix('=')?.trim_start();
    let digits = tail
        .chars()
        .take_while(|ch| ch.is_ascii_digit())
        .collect::<String>();
    (!digits.is_empty()).then(|| digits.parse().ok()).flatten()
}

fn parallel_fan_out_rows(
    rows: Vec<Vec<String>>,
    requested_workers: usize,
) -> (Vec<Vec<String>>, usize) {
    if rows.is_empty() {
        return (rows, 0);
    }
    let worker_count = requested_workers.max(1).min(rows.len());
    if worker_count == 1 {
        return (rows, 1);
    }
    let chunk_size = rows.len().div_ceil(worker_count);
    let mut completed = std::thread::scope(|scope| {
        let mut workers = Vec::with_capacity(worker_count);
        for (index, chunk) in rows.chunks(chunk_size).enumerate() {
            workers.push(scope.spawn(move || (index, chunk.to_vec())));
        }
        workers
            .into_iter()
            .map(|worker| worker.join().expect("IMPORT INTO worker panicked"))
            .collect::<Vec<_>>()
    });
    completed.sort_by_key(|(index, _)| *index);
    (
        completed.into_iter().flat_map(|(_, chunk)| chunk).collect(),
        worker_count,
    )
}

fn hidden_rowid_next_for_files(
    files: &[(String, Vec<u8>)],
    rows_per_file: &[usize],
    column_count: usize,
) -> i64 {
    let mut range_start = 1i64;
    let mut max_used = 0i64;
    for ((name, content), row_count) in files.iter().zip(rows_per_file) {
        let decoded_size = decompress_by_name(name, content).len();
        let reserved = decoded_size
            .div_ceil(column_count.max(1))
            .max(*row_count)
            .max(1) as i64;
        if *row_count > 0 {
            max_used = max_used.max(range_start + *row_count as i64 - 1);
        }
        range_start += reserved;
    }
    max_used + 1
}

