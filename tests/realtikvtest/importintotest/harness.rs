#[derive(Clone, Debug)]
struct AutoIdState {
    auto_increment_next: Option<i64>,
    hidden_rowid_next: Option<i64>,
    separate_auto_increment: bool,
}

impl AutoIdState {
    fn new(has_auto_increment: bool, has_hidden_rowid: bool, separate: bool) -> Self {
        Self {
            auto_increment_next: has_auto_increment.then_some(1),
            hidden_rowid_next: has_hidden_rowid.then_some(1),
            separate_auto_increment: separate,
        }
    }

    fn rebase_auto_increment(&mut self, next: i64) {
        if let Some(current) = &mut self.auto_increment_next {
            *current = (*current).max(next);
        }
        self.synchronize_shared_allocator();
    }

    fn rebase_hidden_rowid(&mut self, next: i64) {
        if let Some(current) = &mut self.hidden_rowid_next {
            *current = (*current).max(next);
        }
        self.synchronize_shared_allocator();
    }

    fn synchronize_shared_allocator(&mut self) {
        if self.separate_auto_increment {
            return;
        }
        if let (Some(auto), Some(rowid)) = (self.auto_increment_next, self.hidden_rowid_next) {
            let shared = auto.max(rowid);
            self.auto_increment_next = Some(shared);
            self.hidden_rowid_next = Some(shared);
        }
    }

    fn allocate_auto_increment(&mut self) -> Option<i64> {
        let id = self.auto_increment_next?;
        self.auto_increment_next = Some(id + 1);
        self.synchronize_shared_allocator();
        Some(id)
    }

    fn global_ids(&self) -> Vec<i64> {
        match (self.auto_increment_next, self.hidden_rowid_next) {
            (Some(auto), Some(rowid)) if self.separate_auto_increment => vec![auto, rowid],
            (Some(auto), Some(_)) => vec![auto],
            (Some(auto), None) => vec![auto],
            (None, Some(rowid)) => vec![rowid],
            (None, None) => Vec::new(),
        }
    }
}

