fn resource_plan(total_real_size: i64, ddl: &str, amplify_factor: f64) -> (i32, i32) {
    const GIB: f64 = (1024u64 * 1024 * 1024) as f64;
    let cpu = mocked_cpu_count().max(1);
    let column_count = ddl_column_names(ddl).len().max(1);
    let lower = ddl.to_ascii_lowercase();
    let secondary_indexes = lower.matches("unique(").count()
        + lower.matches("unique (").count()
        + lower.matches(" key ").count()
        + lower.matches(" index ").count();
    let index_size_ratio = secondary_indexes as f64 / column_count as f64;
    let planned_size = amplify_factor * total_real_size.max(0) as f64 * (1.0 + index_size_ratio);
    let required_slots = (planned_size / (25.0 * GIB)).round().clamp(1.0, cpu as f64) as i32;
    let max_node_limit = (amplify_factor * 32.0 * 8.0 / cpu as f64).max(1.0);
    let max_nodes = (planned_size * 8.0 / cpu as f64 / (200.0 * GIB))
        .round()
        .clamp(1.0, max_node_limit) as i32;
    (required_slots, max_nodes)
}

