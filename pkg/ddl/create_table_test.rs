use astersql_meta_metabuild as metabuild;
use astersql_parser_ast as ast;

use crate::BuildTableInfoFromAST;

fn parse_create(sql: &str) -> Box<ast::CreateTableStmt> {
    let mut parser = astersql_parser::New();
    let statement = parser
        .ParseOneStmt(sql, "", "")
        .expect("parse CREATE TABLE");
    let create = statement
        .as_any()
        .downcast_ref::<ast::CreateTableStmt>()
        .expect("CREATE TABLE AST");
    Box::new(ast::CreateTableStmt {
        node_text: Default::default(),
        IfNotExists: create.IfNotExists,
        TemporaryKeyword: create.TemporaryKeyword,
        OnCommitDelete: create.OnCommitDelete,
        Table: create.Table.clone(),
        ReferTable: create.ReferTable.clone(),
        Cols: create.Cols.clone(),
        Constraints: create.Constraints.clone(),
        Options: create.Options.clone(),
        Partition: create.Partition.clone(),
        SplitIndex: create.SplitIndex.clone(),
        OnDuplicate: create.OnDuplicate,
        Select: None,
    })
}

#[test]
fn shard_row_id_bits_matches_go_clustered_error_and_upper_bound() {
    let context = metabuild::NewContext::<(), std::convert::Infallible>(Vec::new());
    let clustered =
        parse_create("create table t (id bigint primary key clustered) shard_row_id_bits = 4");
    let error = BuildTableInfoFromAST(&context, &clustered).expect_err("reject clustered row ID");
    assert_eq!(
        error.to_string(),
        "[ddl:8200]Unsupported shard_row_id_bits for table with primary key as row id"
    );

    let nonclustered = parse_create("create table t (id bigint) shard_row_id_bits = 64");
    let table = BuildTableInfoFromAST(&context, &nonclustered).expect("build table metadata");
    assert_eq!(table.ShardRowIDBits, 15);
    assert_eq!(table.MaxShardRowIDBits, 15);
}

#[test]
fn ttl_suboptions_require_a_ttl_definition_like_go() {
    let context = metabuild::NewContext::<(), std::convert::Infallible>(Vec::new());
    for sql in [
        "create table t (created_at timestamp) ttl_enable = 'on'",
        "create table t (created_at timestamp) ttl_job_interval = '1h'",
    ] {
        let statement = parse_create(sql);
        assert!(
            BuildTableInfoFromAST(&context, &statement).is_err(),
            "{sql}"
        );
    }
}

#[test]
fn postgresql_identity_metadata_validates_type_and_declarations() {
    let mut parser = astersql_parser::Parser::with_dialect(ast::SqlDialect::PostgreSQL);
    let context = metabuild::NewContext::<(), std::convert::Infallible>(Vec::new());
    for (ty, maximum) in [
        ("smallint", i16::MAX as i64),
        ("integer", i32::MAX as i64),
        ("bigint", i64::MAX),
    ] {
        let stmt = parser
            .ParseOneStmt(
                &format!("CREATE TABLE t (id {ty} GENERATED BY DEFAULT AS IDENTITY)"),
                "",
                "",
            )
            .unwrap();
        let table = BuildTableInfoFromAST(
            &context,
            stmt.as_any()
                .downcast_ref::<ast::CreateTableStmt>()
                .unwrap(),
        )
        .unwrap();
        let column = &table.Columns[0];
        let identity = column.PostgreSQLIdentity.as_ref().unwrap();
        assert!(!identity.Always);
        assert_eq!(identity.SequenceID, 0);
        assert_eq!(identity.Sequence.MaxValue, maximum);
        assert!(astersql_parser_mysql::r#type::HasNotNullFlag(
            column.GetFlag()
        ));
        assert!(!astersql_parser_mysql::r#type::HasAutoIncrementFlag(
            column.GetFlag()
        ));
        assert!(table.Indices.is_empty());
        assert!(column.DefaultValue.is_none());
    }
    for definition in [
        "text GENERATED ALWAYS AS IDENTITY",
        "smallint GENERATED ALWAYS AS IDENTITY (MAXVALUE 32768)",
        "integer GENERATED ALWAYS AS IDENTITY DEFAULT 4",
        "integer GENERATED ALWAYS AS IDENTITY NULL",
        "integer GENERATED ALWAYS AS IDENTITY (START 10 START 20)",
        "integer GENERATED ALWAYS AS IDENTITY (CACHE 0)",
        "integer GENERATED ALWAYS AS IDENTITY (INCREMENT 0)",
    ] {
        let stmt = parser
            .ParseOneStmt(&format!("CREATE TABLE t (id {definition})"), "", "")
            .unwrap();
        assert!(
            BuildTableInfoFromAST(
                &context,
                stmt.as_any()
                    .downcast_ref::<ast::CreateTableStmt>()
                    .unwrap()
            )
            .is_err(),
            "{definition}"
        );
    }
}

#[test]
fn pg13_009_preserves_declared_modifiers() {
    let context = metabuild::NewContext::<(), std::convert::Infallible>(Vec::new());
    let mut parser = astersql_parser::Parser::with_dialect(ast::SqlDialect::PostgreSQL);
    let (statements, _) = parser.ParseSQL("CREATE TABLE decl_types(n numeric, neg numeric(8,-2), t timestamp, p timestamp(3), v varchar(24), a integer[])", &[]).unwrap();
    let statement = statements[0]
        .as_any()
        .downcast_ref::<ast::CreateTableStmt>()
        .unwrap();
    let table = BuildTableInfoFromAST(&context, statement).unwrap();
    assert_eq!(
        (table.Columns[0].GetFlen(), table.Columns[0].GetDecimal()),
        (-1, -1)
    );
    assert_eq!(
        (table.Columns[1].GetFlen(), table.Columns[1].GetDecimal()),
        (8, -2)
    );
    assert_eq!(table.Columns[2].GetDecimal(), -1);
    assert_eq!(table.Columns[3].GetDecimal(), 3);
    assert_eq!(table.Columns[4].FieldType.PostgreSQLTextOid(), Some(1043));
    assert!(
        table.Columns[5]
            .FieldType
            .PostgreSQLArrayElement()
            .is_some()
    );
    let native = BuildTableInfoFromAST(
        &context,
        &parse_create("CREATE TABLE native_types(n decimal, t datetime)"),
    )
    .unwrap();
    assert_eq!(
        (native.Columns[0].GetFlen(), native.Columns[0].GetDecimal()),
        (10, 0)
    );
    assert_eq!(native.Columns[1].GetDecimal(), 0);
}
