// MySQL 兼容但 TiDB 仅提供 noop（空操作）实现的系统变量表与校验逻辑。
//
// noop 变量可被 SET/SHOW，但功能未真正实现；由 `tidb_enable_noop_functions`
//（NoopMode）控制：Off 拒绝、Warn 告警、On 放行。表体 `NOOP_SYS_VARS` 须与 Go
// 兼容表保持同规模，不可随意缩减。

/// 系统变量作用域：无 / 仅全局 / 仅会话 / 全局与会话均可。
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Scope {
    None,
    Global,
    Session,
    GlobalAndSession,
}

/// noop 功能开关模式，对应 `tidb_enable_noop_functions`。
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum NoopMode {
    Off,
    On,
    Warn,
}

/// 系统变量值类型（字符串、布尔、无符号/有符号整数、枚举）。
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum SysVarType {
    String,
    Bool,
    Unsigned,
    Int,
    Enum,
}

/// 校验成功结果：规范化后的值，以及可选的警告消息。
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ValidationResult {
    pub value: String,
    pub warning: Option<String>,
}

/// 校验失败：建议回落值与错误消息。
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ValidationError {
    pub value: String,
    pub message: String,
}

/// 一条 noop 系统变量的元数据（作用域、默认值、类型、别名等）。
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct NoopSysVar {
    pub scope: Scope,
    pub name: &'static str,
    pub value: &'static str,
    pub var_type: SysVarType,
    pub min_value: Option<&'static str>,
    pub max_value: Option<&'static str>,
    pub possible_values: &'static [&'static str],
    pub aliases: &'static [&'static str],
    pub auto_convert_negative_bool: bool,
    pub is_hint_updatable_verified: bool,
    pub read_only: bool,
}

impl NoopSysVar {
    /// 按 noop 模式与作用域校验赋值；受保护只读类变量在 Off/Warn 下特殊处理。
    pub fn validate(
        &self,
        normalized: &str,
        original: &str,
        scope: Scope,
        noop_mode: NoopMode,
        offline: bool,
    ) -> Result<ValidationResult, ValidationError> {
        // 受保护变量：开启只读/离线相关能力时需受 NoopMode 约束。
        let protected = matches!(
            self.name,
            "tx_read_only"
                | "transaction_read_only"
                | "offline_mode"
                | "super_read_only"
                | "read_only"
                | "sql_auto_is_null"
        );
        if protected && matches!(normalized.to_ascii_uppercase().as_str(), "1" | "ON") {
            let feature = if offline {
                "OFFLINE MODE"
            } else if self.name == "sql_auto_is_null" {
                "sql_auto_is_null"
            } else {
                "READ ONLY"
            };
            let message = format!(
                "function {feature} has only noop implementation in tidb now, use tidb_enable_noop_functions to enable these functions"
            );
            if matches!(scope, Scope::Session | Scope::GlobalAndSession) {
                match noop_mode {
                    NoopMode::Off => {
                        // 拒绝开启，回落 OFF。
                        return Err(ValidationError {
                            value: "OFF".into(),
                            message,
                        });
                    }
                    NoopMode::Warn => {
                        // 允许设置但附带警告。
                        return Ok(ValidationResult {
                            value: normalized.into(),
                            warning: Some(message),
                        });
                    }
                    NoopMode::On => {}
                }
            }
            // 全局作用域在 Off 模式下同样拒绝。
            if matches!(scope, Scope::Global) && matches!(noop_mode, NoopMode::Off) {
                return Err(ValidationError {
                    value: "OFF".into(),
                    message,
                });
            }
        }
        // secure_auth 不允许关闭（MySQL 兼容约束）。
        if self.name == "secure_auth"
            && matches!(normalized.to_ascii_uppercase().as_str(), "0" | "OFF")
        {
            return Err(ValidationError {
                value: normalized.into(),
                message: format!(
                    "Variable 'secure_auth' can't be set to the value of '{original}'"
                ),
            });
        }
        Ok(ValidationResult {
            value: normalized.into(),
            warning: None,
        })
    }
}

