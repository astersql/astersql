fn write_equals_method(output: &mut String, operator: &OperatorSpec) {
    line(
        output,
        0,
        &format!(
            "// Equals implements the Hash64Equals interface, only receive *{} pointer.",
            operator.name
        ),
    );
    line(
        output,
        0,
        &format!("func (p *{}) Equals(other any) bool {{", operator.name),
    );
    line(output, 1, &format!("op2, ok := other.(*{})", operator.name));
    line(output, 1, "if !ok {");
    line(output, 2, "return false");
    line(output, 1, "}");
    line(output, 1, "if p == nil {");
    line(output, 2, "return op2 == nil");
    line(output, 1, "}");
    line(output, 1, "if op2 == nil {");
    line(output, 2, "return false");
    line(output, 1, "}");
    if operator.fields.is_empty() {
        line(output, 1, "_ = op2");
    }
    for field in &operator.fields {
        write_equals_element(
            output,
            &field.kind,
            &format!("p.{}", field.name),
            &format!("op2.{}", field.name),
            "i",
            1,
        );
    }
    line(output, 1, "return true");
    line(output, 0, "}");
    output.push('\n');
}

fn write_equals_element(
    output: &mut String,
    field_type: &FieldType,
    lhs: &str,
    rhs: &str,
    index: &str,
    indent: usize,
) {
    match field_type {
        FieldType::Slice(element) => {
            line(
                output,
                indent,
                &format!(
                    "if ({lhs} == nil && {rhs} != nil) || ({lhs} != nil && {rhs} == nil) || len({lhs}) != len({rhs}) {{"
                ),
            );
            line(output, indent + 1, "return false");
            line(output, indent, "}");
            let item_name = nested_item_name(lhs);
            line(
                output,
                indent,
                &format!("for {index}, {item_name} := range {lhs} {{"),
            );
            write_equals_element(
                output,
                element,
                &item_name,
                &format!("{rhs}[{index}]"),
                &format!("{index}i"),
                indent + 1,
            );
            line(output, indent, "}");
        }
        FieldType::Bool
        | FieldType::SignedInteger
        | FieldType::UnsignedInteger
        | FieldType::Float
        | FieldType::String => {
            line(output, indent, &format!("if {lhs} != {rhs} {{"));
            line(output, indent + 1, "return false");
            line(output, indent, "}");
        }
        FieldType::HashEqualsValue => {
            line(output, indent, &format!("if !{lhs}.Equals(&{rhs}) {{"));
            line(output, indent + 1, "return false");
            line(output, indent, "}");
        }
        FieldType::HashEqualsPointer | FieldType::HashEqualsDirect => {
            line(output, indent, &format!("if !{lhs}.Equals({rhs}) {{"));
            line(output, indent + 1, "return false");
            line(output, indent, "}");
        }
    }
}

fn nested_item_name(call_name: &str) -> String {
    if call_name.starts_with("one") {
        format!("{call_name}e")
    } else {
        "one".to_owned()
    }
}

fn line(output: &mut String, indent: usize, text: &str) {
    for _ in 0..indent {
        output.push('\t');
    }
    output.push_str(text);
    output.push('\n');
}

