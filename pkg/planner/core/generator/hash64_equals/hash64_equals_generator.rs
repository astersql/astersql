//! Generates the Go `Hash64` and `Equals` methods for logical operators.
//!
//! Go discovers participating fields through reflection and the
//! `hash64-equals:"true"` struct tag. Rust cannot reflect over Go types, so the
//! same field/type information is represented explicitly below. The recursive
//! emitter otherwise follows the Go generator's pointer, slice, scalar and
//! `HashEquals` branches exactly.

#[derive(Clone, Debug, PartialEq, Eq)]
/// Public field kinds accepted by the metadata-driven generator API.
pub enum HashFieldKind {
    Bool,
    Integer,
    UnsignedInteger,
    Float,
    String,
    Bytes,
    Pointer,
    Slice,
    Interface,
    HashEquals,
    Ignored,
}

#[derive(Clone, Debug, PartialEq, Eq)]
/// One field carrying the Go `hash64-equals:"true"` tag.
pub struct HashField {
    pub name: String,
    pub kind: HashFieldKind,
}

#[derive(Clone, Debug, PartialEq, Eq)]
/// One logical operator and the fields used by its generated methods.
pub struct LogicalOperator {
    pub name: String,
    pub codec_name: String,
    pub fields: Vec<HashField>,
}

#[derive(Clone, Debug)]
enum FieldType {
    Bool,
    SignedInteger,
    UnsignedInteger,
    Float,
    String,
    /// A value whose `Equals` argument must be addressed (a Go struct value).
    HashEqualsValue,
    /// A pointer whose hash must encode nil/non-nil at the tagged-field level.
    HashEqualsPointer,
    /// An interface or other HashEquals value whose `Equals` argument is direct.
    HashEqualsDirect,
    Slice(Box<FieldType>),
}

#[derive(Clone, Debug)]
struct FieldSpec {
    name: String,
    kind: FieldType,
}

#[derive(Clone, Debug)]
struct OperatorSpec {
    name: String,
    codec_name: String,
    fields: Vec<FieldSpec>,
}

