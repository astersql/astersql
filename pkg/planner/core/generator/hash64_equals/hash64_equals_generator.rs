/// Generate complete, gofmt-shaped source for explicitly described operators.
pub fn gen_hash64_equals_for_logical_ops(operators: &[LogicalOperator]) -> Result<Vec<u8>, String> {
    let mut specs = Vec::with_capacity(operators.len());
    for operator in operators {
        validate_name(&operator.name)?;
        let fields = operator
            .fields
            .iter()
            .filter_map(public_field_spec)
            .collect();
        specs.push(OperatorSpec {
            name: operator.name.clone(),
            codec_name: operator.codec_name.clone(),
            fields,
        });
    }
    generate(&specs)
}

fn public_field_spec(field: &HashField) -> Option<FieldSpec> {
    let kind = match field.kind {
        HashFieldKind::Bool => FieldType::Bool,
        HashFieldKind::Integer => FieldType::SignedInteger,
        HashFieldKind::UnsignedInteger => FieldType::UnsignedInteger,
        HashFieldKind::Float => FieldType::Float,
        HashFieldKind::String => FieldType::String,
        HashFieldKind::Bytes => FieldType::Slice(Box::new(FieldType::UnsignedInteger)),
        HashFieldKind::Pointer => FieldType::HashEqualsPointer,
        HashFieldKind::Slice => FieldType::Slice(Box::new(FieldType::HashEqualsDirect)),
        HashFieldKind::Interface => FieldType::HashEqualsDirect,
        HashFieldKind::HashEquals => FieldType::HashEqualsValue,
        HashFieldKind::Ignored => return None,
    };
    Some(FieldSpec {
        name: field.name.clone(),
        kind,
    })
}

fn generate(operators: &[OperatorSpec]) -> Result<Vec<u8>, String> {
    let mut output = String::from(CODE_GEN_HASH64_EQUALS_PREFIX);
    output.push('\n');
    for operator in operators {
        validate_name(&operator.name)?;
        write_hash_method(&mut output, operator);
        write_equals_method(&mut output, operator);
    }
    if !operators.is_empty() {
        output.pop();
    }
    Ok(output.into_bytes())
}

