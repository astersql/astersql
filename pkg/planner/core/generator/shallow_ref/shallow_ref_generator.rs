/// Generate complete, gofmt-shaped source for explicitly described operators.
pub fn gen_shallow_ref_for_logical_ops(operators: &[LogicalOperator]) -> Result<Vec<u8>, String> {
    let mut output = String::from(
        "// Copyright 2025 PingCAP, Inc.\n// Code generated by shallow_ref_generator; DO NOT EDIT.\n\npackage logicalop\n\n",
    );
    for operator in operators {
        validate_name(&operator.name)?;
        output.push_str(&format!(
            "func (p *{}) ShallowRef() *{} {{\n",
            operator.name, operator.name
        ));
        output.push_str("\tif p == nil { return nil }\n\tr := *p\n");
        for field in &operator.fields {
            validate_name(&field.name)?;
            if !field.exported {
                continue;
            }
            match field.kind {
                FieldKind::Slice => output.push_str(&format!(
                    "\tr.{0} = append([]{1}(nil), p.{0}...)\n",
                    field.name,
                    field.type_name.trim_start_matches("[]")
                )),
                FieldKind::Map => output.push_str(&format!(
                    "\tif p.{0} != nil {{ r.{0} = maps.Clone(p.{0}) }}\n",
                    field.name
                )),
                FieldKind::ShallowRef => {
                    output.push_str(&format!("\tr.{0} = p.{0}.ShallowRef()\n", field.name));
                }
                FieldKind::Value
                | FieldKind::Pointer
                | FieldKind::Interface
                | FieldKind::Embedded => {}
            }
        }
        output.push_str("\treturn &r\n}\n\n");
    }
    Ok(output.into_bytes())
}

