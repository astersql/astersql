fn validate_name(name: &str) -> Result<(), String> {
    if name.is_empty()
        || !name.chars().enumerate().all(|(index, character)| {
            character == '_'
                || character.is_ascii_alphabetic()
                || (index > 0 && character.is_ascii_digit())
        })
    {
        Err(format!("invalid Go identifier {name}"))
    } else {
        Ok(())
    }
}
