fn write_shallow_ref_element(
    output: &mut String,
    field_type: &TypeSpec,
    caller: &str,
    field_name: &str,
    indent: usize,
) -> Result<Option<String>, String> {
    match field_type {
        TypeSpec::Scalar => Ok(None),
        TypeSpec::Slice { go_name, element } => {
            let temporary = format!("{field_name}CP");
            line(
                output,
                indent,
                &format!("{temporary} := make({go_name}, 0, len({caller}{field_name}))"),
            );
            let item_name = if field_name.starts_with("one") {
                format!("{field_name}e")
            } else {
                "one".to_owned()
            };
            line(
                output,
                indent,
                &format!("for _, {item_name} := range {caller}{field_name} {{"),
            );
            let nested = write_shallow_ref_element(output, element, "", &item_name, indent + 1)?;
            let result = nested.as_deref().unwrap_or(&item_name);
            line(
                output,
                indent + 1,
                &format!("{temporary} = append({temporary}, {result})"),
            );
            line(output, indent, "}");
            if field_name.starts_with("one") {
                return Ok(Some(temporary));
            }
            line(
                output,
                indent,
                &format!("{caller}{field_name} = {temporary}"),
            );
            Ok(None)
        }
        TypeSpec::Struct { fields } => {
            let temporary = format!("{field_name}CP");
            line(
                output,
                indent,
                &format!("{temporary} := {caller}{field_name}"),
            );
            for field in fields.iter().filter(|field| field.exported) {
                write_shallow_ref_element(
                    output,
                    &field.field_type,
                    &format!("{temporary}."),
                    &field.name,
                    indent,
                )?;
            }
            if !field_name.starts_with("one") {
                line(
                    output,
                    indent,
                    &format!("{caller}{field_name} = {temporary}"),
                );
            }
            Ok(Some(temporary))
        }
        TypeSpec::Unsupported(kind) => Err(format!("doesn't support element type{kind}")),
    }
}

