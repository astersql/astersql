impl CloneForPlanCache for PhysicalIndexJoin {
    fn clone_for_plan_cache(&self) -> Option<Self> {
        let context = self
            .BasePhysicalJoin
            .PhysicalSchemaProducer
            .BasePhysicalPlan
            .Plan
            .SCtx()
            .clone();
        Some(Self {
            BasePhysicalJoin: self
                .BasePhysicalJoin
                .CloneForPlanCacheWithSelf(context.clone())?,
            InnerPlan: self
                .InnerPlan
                .as_ref()
                .map(|plan| plan.clone_physical(context))
                .transpose()
                .ok()?,
            Ranges: self.Ranges.clone(),
            KeyOff2IdxOff: self.KeyOff2IdxOff.clone(),
            IdxColLens: self.IdxColLens.clone(),
            CompareFilters: self
                .CompareFilters
                .as_ref()
                .map(crate::physical_index_join::ColWithCmpFuncManager::cloneForPlanCache),
            OuterHashKeys: self
                .OuterHashKeys
                .iter()
                .map(expression::Column::Clone)
                .collect(),
            InnerHashKeys: self
                .InnerHashKeys
                .iter()
                .map(expression::Column::Clone)
                .collect(),
            EqualConditions: self
                .EqualConditions
                .iter()
                .map(expression::ScalarFunction::clone_scalar)
                .collect(),
            FromDecorrelatedApply: self.FromDecorrelatedApply,
        })
    }
}
/// 克隆 Insert；SelectPlan 不可缓存时整体失败。
impl CloneForPlanCache for Insert {
    fn clone_for_plan_cache(&self) -> Option<Self> {
        if !self.fk_checks.is_empty() || !self.fk_cascades.is_empty() {
            return None;
        }
        let mut cloned = self.clone();
        cloned.select_plan = self
            .select_plan
            .as_ref()
            .map(CloneForPlanCache::clone_for_plan_cache)
            .transpose_option()?;
        Some(cloned)
    }
}
