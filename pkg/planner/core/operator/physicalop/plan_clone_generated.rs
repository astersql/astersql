/// Plan Cache 克隆：成功返回副本，失败（不可缓存字段）返回 None。
pub trait CloneForPlanCache: Sized {
    /// 尝试克隆自身供缓存复用。
    fn clone_for_plan_cache(&self) -> Option<Self>;
}
/// 递归克隆通用物理计划节点及其 children。
impl CloneForPlanCache for PhysicalPlanNode {
    fn clone_for_plan_cache(&self) -> Option<Self> {
        let mut cloned = self.clone();
        cloned.children = self
            .children
            .iter()
            .map(CloneForPlanCache::clone_for_plan_cache)
            .collect::<Option<Vec<_>>>()?;
        Some(cloned)
    }
}
impl CloneForPlanCache for PhysicalHashJoin {
    fn clone_for_plan_cache(&self) -> Option<Self> {
        if !self.RuntimeFilterList.is_empty() {
            return None;
        }
        Some(Self {
            BasePhysicalJoin: self.BasePhysicalJoin.CloneForPlanCacheWithSelf(
                self.BasePhysicalJoin
                    .PhysicalSchemaProducer
                    .BasePhysicalPlan
                    .Plan
                    .SCtx()
                    .clone(),
            )?,
            Concurrency: self.Concurrency,
            EqualConditions: self
                .EqualConditions
                .iter()
                .map(expression::ScalarFunction::clone_scalar)
                .collect(),
            NAEqualConditions: self
                .NAEqualConditions
                .iter()
                .map(expression::ScalarFunction::clone_scalar)
                .collect(),
            UseOuterToBuild: self.UseOuterToBuild,
            StoreTp: self.StoreTp,
            MppShuffleJoin: self.MppShuffleJoin,
            FromHashJoinHint: self.FromHashJoinHint,
            HasTableAlias: self.HasTableAlias,
            RuntimeFilterList: Vec::new(),
            RuntimeFilterTypes: self.RuntimeFilterTypes.clone(),
        })
    }
}
