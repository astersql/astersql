impl Scanner {
    // isTokenIdentifier 先排除限定名，再做 ASCII 大写化与函数/普通/窗口关键字三级查表。
    /// 将标识符解析为关键字/内建/窗口函数 token，排除限定名。
    pub fn isTokenIdentifier(&mut self, lit: &str, token_offset: i32) -> i32 {
        // 点号两侧的词属于 qualified identifier，不能解释为 SQL 关键字。
        if self.r.peek() == b'.' {
            return 0;
        }
        let bytes = self.r.s.as_bytes();
        let mut idx = token_offset - 1;
        while idx >= 0 {
            match bytes[idx as usize] {
                b' ' => idx -= 1,
                b'.' => return 0,
                _ => break,
            }
        }
        self.buf.clear();
        self.buf.reserve(lit.len());
        self.buf.extend(lit.bytes().map(|c| {
            if c.is_ascii_lowercase() {
                c.to_ascii_uppercase()
            } else {
                c
            }
        }));
        let normalized = String::from_utf8_lossy(&self.buf).into_owned();

        // IGNORE_SPACE 模式允许函数名与左括号之间存在空白；skipWhitespace 会推进 reader，沿用 Go 行为。
        let mut builtin_call = self.r.peek() == b'(';
        if !builtin_call && self.sqlMode.HasIgnoreSpaceMode() {
            self.skipWhitespace();
            builtin_call = self.r.peek() == b'(';
        }
        if builtin_call {
            let tok = lookup_token(btFuncTokenMap, &normalized);
            if tok != 0 {
                return tok;
            }
        }
        let tok = lookup_token(tokenMap, &normalized);
        if tok == 0 && self.supportWindowFunc {
            lookup_token(windowFuncTokenMap, &normalized)
        } else {
            tok
        }
    }
}
