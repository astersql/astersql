// 词法辅助：字符分类、运算符规则树（trie）与关键字/Hint token 映射表。
//
// `ruleTable` 按字节最长匹配分派到 `lexer.rs` 中的扫描函数；
// `isTokenIdentifier` 在标识符路径上查普通关键字、内建函数与窗口函数表。

// 在内存中识别 SQL token。
use std::sync::LazyLock as MiscLazyLock;

// ASCII 字母、数字与非 ASCII 扩展字节的分类规则和 Go 完全一致。
/// 判断 ASCII 字母。
pub fn isLetter(ch: u8) -> bool {
    ch.is_ascii_alphabetic()
}
/// 判断 ASCII 数字。
pub fn isDigit(ch: u8) -> bool {
    ch.is_ascii_digit()
}
/// 标识符允许的字节（含 `$`/`_`/扩展）。
pub fn isIdentChar(ch: u8) -> bool {
    isLetter(ch) || isDigit(ch) || ch == b'_' || ch == b'$' || isIdentExtend(ch)
}
/// 非 ASCII 扩展标识符字节。
pub fn isIdentExtend(ch: u8) -> bool {
    ch >= 0x80
}

// isInCorrectIdentifierName 保留原函数的反向命名语义：空名称或尾随空格返回 true。
/// 非法标识符名（空或尾随空格）；保留 Go 反向命名。
pub fn isInCorrectIdentifierName(name: &str) -> bool {
    name.is_empty() || name.as_bytes().last() == Some(&b' ')
}

// Go 在 init 中填充 256 项查表；Rust 用同一谓词表达，避免每次初始化可变全局状态。
/// 用户变量名允许的字符（含 `.`）。
pub fn isUserVarChar(ch: u8) -> bool {
    isLetter(ch) || isDigit(ch) || ch == b'_' || ch == b'$' || ch == b'.' || isIdentExtend(ch)
}

// trieNode 对应单字节 token trie；function 保存 lexer.rs 中的分支扫描函数。
/// 单字节 token trie 节点，可挂接扫描函数。
pub struct trieNode {
    pub childs: Vec<Option<Box<trieNode>>>,
    pub token: i32,
    pub function: Option<fn(&mut Scanner) -> (i32, Pos, String)>,
}
impl trieNode {
    /// 构造 256 子槽的空节点。
    fn new() -> Self {
        Self {
            childs: (0..256).map(|_| None).collect(),
            token: 0,
            function: None,
        }
    }
}

// initTokenByte/String/Func 对应 Go 初始化辅助函数；调用方传入局部 root 后再发布为 ruleTable。
/// 注册单字节 token。
fn initTokenByte(root: &mut trieNode, c: u8, tok: i32) {
    let node = root.childs[c as usize].get_or_insert_with(|| Box::new(trieNode::new()));
    node.token = tok;
}
/// 沿字符串路径注册多字节运算符 token。
fn initTokenString(root: &mut trieNode, text: &str, tok: i32) {
    let mut node = root;
    for c in text.bytes() {
        node = node.childs[c as usize].get_or_insert_with(|| Box::new(trieNode::new()));
    }
    node.token = tok;
}
/// 为 text 中每个首字节挂接扫描函数（Go 语义）。
fn initTokenFunc(
    root: &mut trieNode,
    text: &str,
    scanner_fn: fn(&mut Scanner) -> (i32, Pos, String),
) {
    // Go 对 text 的每个字节都从 root 挂函数，而不是构造多级路径。
    for c in text.bytes() {
        let node = root.childs[c as usize].get_or_insert_with(|| Box::new(trieNode::new()));
        node.function = Some(scanner_fn);
    }
}

// buildRuleTable 保留两个 Go init 的效果：默认 invalid、固定符号、复合运算符及分派函数。
/// 构建完整运算符/分派规则树。
pub fn buildRuleTable() -> trieNode {
    let mut root = trieNode::new();
    root.token = invalid;
    for (c, tok) in [
        (b'/', b'/' as i32),
        (b'+', b'+' as i32),
        (b'>', b'>' as i32),
        (b'<', b'<' as i32),
        (b'(', b'(' as i32),
        (b')', b')' as i32),
        (b'[', b'[' as i32),
        (b']', b']' as i32),
        (b';', b';' as i32),
        (b',', b',' as i32),
        (b'&', b'&' as i32),
        (b'%', b'%' as i32),
        (b':', b':' as i32),
        (b'|', b'|' as i32),
        (b'!', b'!' as i32),
        (b'^', b'^' as i32),
        (b'~', b'~' as i32),
        (b'\\', b'\\' as i32),
        (b'?', token::paramMarker),
        (b'=', token::eq),
        (b'{', b'{' as i32),
        (b'}', b'}' as i32),
    ] {
        initTokenByte(&mut root, c, tok);
    }
    for (text, tok) in [
        ("||", token::pipes),
        ("&&", token::andand),
        ("&^", token::andnot),
        (":=", token::assignmentEq),
        ("<=>", token::nulleq),
        (">=", token::ge),
        ("<=", token::le),
        ("!=", token::neq),
        ("<>", token::neqSynonym),
        ("<<", token::lsh),
        (">>", token::rsh),
        ("\\N", token::null),
    ] {
        initTokenString(&mut root, text, tok);
    }
    for (text, scanner_fn) in [
        ("@", startWithAt as fn(&mut Scanner) -> _),
        ("/", startWithSlash),
        ("*", startWithStar),
        ("-", startWithDash),
        ("#", startWithSharp),
        ("Xx", startWithXx),
        ("Nn", startWithNn),
        ("Bb", startWithBb),
        (".", startWithDot),
        (
            "_$ACDEFGHIJKLMOPQRSTUVWYZacdefghijklmopqrstuvwyz",
            scanIdentifier,
        ),
        ("`", scanQuotedIdent),
        ("0123456789", startWithNumber),
        ("'\"", startString),
    ] {
        initTokenFunc(&mut root, text, scanner_fn);
    }
    root
}

// ruleTable 对应 Go 包级 trie；LazyLock 保证首次扫描前只初始化一次。
/// 包级懒初始化规则树。
pub static ruleTable: MiscLazyLock<trieNode> = MiscLazyLock::new(buildRuleTable);

/// 在 (名称, token) 表中精确查找。
fn lookup_token(map: &[(&str, i32)], target_name: &str) -> i32 {
    map.iter()
        .find_map(|(name, tok)| (*name == target_name).then_some(*tok))
        .unwrap_or(0)
}

// isInTokenMap 判断规范化后的标识符是否属于 parser 已知关键字。
/// 是否为已知关键字。
pub fn isInTokenMap(target_name: &str) -> bool {
    lookup_token(tokenMap, target_name) != 0
}

