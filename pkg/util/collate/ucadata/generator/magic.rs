// `reverseHexTable` 供 `parseCETHex` 按字节快速判断十六进制数值。

// LongRune8 means the rune has at most 8 collation elements
/// 与 `ucadata/data` 同名：MapTable 中表示该 rune 有最多 8 个一级权重。
