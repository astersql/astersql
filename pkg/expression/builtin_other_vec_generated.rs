/// JSON IN：不建哈希，仅逐参数 CompareBinaryJSON。
pub struct BuiltinInJsonSig {
    args: Expressions,
}

impl BuiltinInJsonSig {
    pub fn new(args: Expressions) -> Self {
        Self { args }
    }

    pub fn vectorized(&self) -> bool {
        true
    }

    pub fn vec_eval_int(
        &self,
        context: &EvalContext,
        input: &chunk::Chunk,
        result: &mut chunk::Column,
    ) -> EvalResult<()> {
        evaluate_in(
            context,
            input,
            result,
            &self.args,
            false,
            &[],
            false,
            |expression, context, input, result| expression.vec_eval_json(context, input, result),
            |column, row| column.GetJSON(row),
            |_| Ok(false),
            |left, right, _| types::CompareBinaryJSON(left, right) == 0,
        )
    }
}

