/// 按策略判定签名是否可跨会话共享。
pub fn generatedSignatureSafeToShareAcrossSession<T, F>(
    signature: Option<&str>,
    flag: &AtomicU32,
    args: &[T],
    is_safe: F,
) -> bool
where
    F: FnMut(&T) -> bool,
{
    match signature.and_then(GeneratedThreadSafetyPolicyForSignature) {
        Some(GeneratedThreadSafetyPolicy::Recursive) => {
            safeToShareAcrossSession(flag, args, is_safe)
        }
        Some(GeneratedThreadSafetyPolicy::Never) | None => false,
    }
}

/// 原子缓存的参数安全探测：0 未缓存，1 安全，2 不安全。
pub fn safeToShareAcrossSession<T, F>(flag: &AtomicU32, args: &[T], mut is_safe: F) -> bool
where
    F: FnMut(&T) -> bool,
{
    let cached = flag.load(Ordering::SeqCst);
    if cached != 0 {
        return cached == 1;
    }

    let safe = args.iter().all(&mut is_safe);
    flag.store(if safe { 1 } else { 2 }, Ordering::SeqCst);
    safe
}

